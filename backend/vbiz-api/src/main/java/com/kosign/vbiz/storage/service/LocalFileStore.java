package com.kosign.vbiz.storage.service;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;

import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty;
import org.springframework.stereotype.Component;

/** Files under {@code vbiz.storage.dir} (one API instance, or a shared volume). The default. */
@Component
@ConditionalOnProperty(name = "vbiz.storage.type", havingValue = "local", matchIfMissing = true)
public class LocalFileStore implements FileStore {

    private final Path root;

    public LocalFileStore(StorageProperties props) throws IOException {
        this.root = Path.of(props.dir()).toAbsolutePath().normalize();
        Files.createDirectories(root);
    }

    @Override
    public void put(String key, byte[] bytes, String contentType) throws IOException {
        Path target = resolve(key);
        Files.createDirectories(target.getParent());
        Path tmp = Files.createTempFile(target.getParent(), ".up-", ".tmp");
        Files.write(tmp, bytes);
        Files.move(tmp, target, StandardCopyOption.REPLACE_EXISTING, StandardCopyOption.ATOMIC_MOVE);
    }

    @Override
    public byte[] get(String key) throws IOException {
        Path p = resolve(key);
        return Files.isRegularFile(p) ? Files.readAllBytes(p) : null;
    }

    /** Keys are generated by the service; still, never let one leave the root. */
    private Path resolve(String key) {
        Path p = root.resolve(key).normalize();
        if (!p.startsWith(root)) {
            throw new IllegalArgumentException("Bad storage key");
        }
        return p;
    }
}
